import SwiftUI
import UniformTypeIdentifiers
import DJBoothKit
#if os(iOS)
import VisionKit
#endif

struct MacPairingView: View {
    @Bindable var model: BoothModel
    @Environment(\.dismiss) private var dismiss
    @State private var input = ""
    @State private var importing = false
    @State private var scanning = false
    @State private var connecting = false
    @State private var error: String?
    private var pairing: PairedLibrary? { try? PairedLibrary(json: Data(input.utf8)) }

    var body: some View {
        NavigationStack {
            Form {
                Section {
                    Text("Browse your Mac’s music without a cloud account. Download tracks and their DJ analysis to use them offline.")
                    Text("Pair only with your own Mac. The pairing code grants read access to its music library.")
                        .font(.caption).foregroundStyle(.secondary)
                }
                Section("Pairing code from your Mac") {
                    #if os(iOS)
                    if DataScannerViewController.isSupported && DataScannerViewController.isAvailable {
                        Button("Scan pairing QR code", systemImage: "qrcode.viewfinder") { scanning = true }
                            .accessibilityIdentifier("pair.scan")
                    }
                    #endif
                    Button("Open pairing file", systemImage: "doc") { importing = true }
                        .accessibilityIdentifier("pair.file")
                    SecureField("Paste pairing code", text: $input)
                        .autocorrectionDisabled().accessibilityIdentifier("pair.code")
                        #if os(iOS)
                        .textInputAutocapitalization(.never)
                        #endif
                    PasteButton(payloadType: String.self) { values in input = values.first ?? ""; error = nil }
                }
                if let pairing {
                    Section("Confirm this Mac") {
                        LabeledContent("Library", value: pairing.name)
                        LabeledContent("Address", value: pairing.url.absoluteString)
                        Text("Encrypted connection · read-only playlists").font(.caption).foregroundStyle(.secondary)
                        Button("Pair and browse library") {
                            connecting = true; error = nil
                            Task {
                                defer { connecting = false }
                                do {
                                    try await model.connectPairedMac(Data(input.utf8))
                                    input = ""; dismiss()
                                } catch { self.error = error.localizedDescription }
                            }
                        }.disabled(connecting).accessibilityIdentifier("pair.connect")
                        Text("The Mac stays connected to your decks. Pairing turns off this phone’s Wi-Fi source sharing; downloading music does not start another source.")
                            .font(.caption).foregroundStyle(.secondary)
                    }
                } else if !input.isEmpty {
                    Text("Use the complete pairing code or file generated by DJBooth on your Mac.")
                        .foregroundStyle(.secondary).accessibilityIdentifier("pair.invalid")
                }
                if connecting { ProgressView("Connecting to your Mac…").accessibilityIdentifier("pair.progress") }
                if let error { Text(error).foregroundStyle(.red).accessibilityIdentifier("pair.error") }
            }.formStyle(.grouped).navigationTitle("Pair with Mac")
                .toolbar { Button("Cancel") { input = ""; dismiss() }.disabled(connecting) }
                .fileImporter(isPresented: $importing, allowedContentTypes: [.json]) { result in
                    do {
                        let url = try result.get()
                        let scoped = url.startAccessingSecurityScopedResource()
                        defer { if scoped { url.stopAccessingSecurityScopedResource() } }
                        let size = try url.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0
                        guard size > 0, size <= 16_384 else { throw ClientError.http(400, "This is not a DJBooth pairing file") }
                        let data = try Data(contentsOf: url)
                        _ = try PairedLibrary(json: data)
                        input = String(decoding: data, as: UTF8.self); error = nil
                    } catch { self.error = "Could not read the pairing file. Choose the JSON file from your Mac." }
                }
                #if os(iOS)
                .fullScreenCover(isPresented: $scanning) {
                    NavigationStack {
                        PairingScanner { value in input = value; scanning = false }
                            .ignoresSafeArea(edges: .bottom)
                            .navigationTitle("Scan Mac pairing code")
                            .toolbar { Button("Cancel") { scanning = false } }
                    }
                }
                #endif
        }
    }
}

#if os(iOS)
private struct PairingScanner: UIViewControllerRepresentable {
    let received: (String) -> Void
    func makeCoordinator() -> Coordinator { Coordinator(received: received) }
    func makeUIViewController(context: Context) -> DataScannerViewController {
        let scanner = DataScannerViewController(recognizedDataTypes: [.barcode(symbologies: [.qr])],
            qualityLevel: .balanced, recognizesMultipleItems: false, isGuidanceEnabled: true, isHighlightingEnabled: true)
        scanner.delegate = context.coordinator
        try? scanner.startScanning()
        return scanner
    }
    func updateUIViewController(_ uiViewController: DataScannerViewController, context: Context) {}
    static func dismantleUIViewController(_ uiViewController: DataScannerViewController, coordinator: Coordinator) { uiViewController.stopScanning() }
    @MainActor final class Coordinator: NSObject, DataScannerViewControllerDelegate {
        let received: (String) -> Void
        private var finished = false
        init(received: @escaping (String) -> Void) { self.received = received }
        func dataScanner(_ dataScanner: DataScannerViewController, didAdd addedItems: [RecognizedItem], allItems: [RecognizedItem]) {
            guard !finished else { return }
            for case .barcode(let barcode) in addedItems {
                guard let value = barcode.payloadStringValue, value.utf8.count <= 16_384,
                      (try? PairedLibrary(json: Data(value.utf8))) != nil else { continue }
                finished = true; dataScanner.stopScanning(); received(value); return
            }
        }
    }
}
#endif
