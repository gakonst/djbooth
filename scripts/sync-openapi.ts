import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'
import { parse } from 'yaml'

const sourceUrl = 'https://developer.spotify.com/reference/web-api/open-api-schema.yaml'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const response = await fetch(sourceUrl)
if (!response.ok) {
  throw new Error(
    `Could not download Spotify OpenAPI schema: ${response.status} ${response.statusText}`,
  )
}

const yaml = await response.text()
const document = stripSpotifyPolicyExtensions(parse(yaml)) as {
  paths?: Record<string, Record<string, { operationId?: string }>>
}

const operations = Object.values(document.paths ?? {}).flatMap((path) =>
  Object.values(path).filter(
    (operation): operation is { operationId?: string } =>
      typeof operation === 'object' && operation !== null && 'responses' in operation,
  ),
)

const schemaAst = await openapiTS(document as never, { alphabetize: true })
const schema = `// Generated by npm run openapi:sync. Do not edit.\n${astToString(schemaAst)}`
const json = `${JSON.stringify(document, null, 2)}\n`
const metadata = {
  source: sourceUrl,
  syncedAt: new Date().toISOString(),
  sha256: createHash('sha256').update(yaml).digest('hex'),
  paths: Object.keys(document.paths ?? {}).length,
  operations: operations.length,
}

await mkdir(resolve(root, 'openapi'), { recursive: true })
await mkdir(resolve(root, 'src/generated'), { recursive: true })
await Promise.all([
  writeFile(resolve(root, 'openapi/spotify.yaml'), yaml),
  writeFile(resolve(root, 'src/generated/spotify-openapi.json'), json),
  writeFile(resolve(root, 'src/generated/spotify-schema.ts'), schema),
  writeFile(resolve(root, 'src/generated/metadata.json'), `${JSON.stringify(metadata, null, 2)}\n`),
])

console.log(`Synced ${metadata.operations} Spotify operations across ${metadata.paths} paths.`)

function stripSpotifyPolicyExtensions(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(stripSpotifyPolicyExtensions)
  if (typeof value !== 'object' || value === null) return value

  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => !key.startsWith('x-spotify-policy'))
      .map(([key, nested]) => [key, stripSpotifyPolicyExtensions(nested)]),
  )
}
