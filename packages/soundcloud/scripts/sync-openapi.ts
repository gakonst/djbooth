import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'
import { parse } from 'yaml'

const sourceUrl =
  'https://raw.githubusercontent.com/soundcloud/api/master/openapi/api.yaml'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const response = await fetch(sourceUrl)
if (!response.ok) {
  throw new Error(
    `Could not download SoundCloud OpenAPI schema: ${response.status} ${response.statusText}`,
  )
}

const yaml = await response.text()
const checkedInYaml = `${yaml.trimEnd()}\n`
const document = parse(yaml) as SoundCloudOpenApi
const operations = addStableOperationIds(document)
const schemaAst = await openapiTS(document as never, { alphabetize: true })
const schema = `// Generated by pnpm openapi:sync. Do not edit.\n${astToString(schemaAst)}`
const incurDocument = structuredClone(document)
normalizeForIncur(incurDocument)
const json = `${JSON.stringify(incurDocument, null, 2)}\n`
const metadata = {
  source: sourceUrl,
  syncedAt: new Date().toISOString(),
  sha256: createHash('sha256').update(yaml).digest('hex'),
  paths: Object.keys(document.paths ?? {}).length,
  operations,
}

await mkdir(resolve(root, 'openapi'), { recursive: true })
await mkdir(resolve(root, 'src/generated'), { recursive: true })
await Promise.all([
  writeFile(resolve(root, 'openapi/soundcloud.yaml'), checkedInYaml),
  writeFile(resolve(root, 'src/generated/soundcloud-openapi.json'), json),
  writeFile(resolve(root, 'src/generated/soundcloud-schema.ts'), schema),
  writeFile(
    resolve(root, 'src/generated/metadata.json'),
    `${JSON.stringify(metadata, null, 2)}\n`,
  ),
])

console.log(
  `Synced ${metadata.operations} SoundCloud operations across ${metadata.paths} paths.`,
)

interface SoundCloudOpenApi {
  paths?: Record<string, Record<string, unknown>>
  security?: unknown[]
}

function addStableOperationIds(document: SoundCloudOpenApi): number {
  let count = 0
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const method of [
      'get',
      'put',
      'post',
      'delete',
      'patch',
      'head',
      'options',
    ] as const) {
      const operation = pathItem[method]
      if (!isRecord(operation) || !('responses' in operation)) continue
      operation.operationId ??= operationId(method, path)
      count += 1
    }
  }
  return count
}

function operationId(method: string, path: string): string {
  const parts = path
    .split('/')
    .filter(Boolean)
    .map((part) =>
      part.replaceAll(/[{}]/g, '').replaceAll(/[^a-zA-Z0-9]+/g, '-'),
    )
  return [method, ...parts].join('-').toLowerCase()
}

function normalizeForIncur(document: SoundCloudOpenApi): void {
  // The configured client supplies OAuth. Keeping the security scheme here would
  // expose a dangerous --authorization argv option in every generated command.
  document.security = []
  normalizeJsonMediaTypes(document)
}

function normalizeJsonMediaTypes(value: unknown): void {
  if (Array.isArray(value)) {
    for (const nested of value) normalizeJsonMediaTypes(nested)
    return
  }
  if (!isRecord(value)) return

  const content = value.content
  if (isRecord(content) && !('application/json' in content)) {
    const jsonEntry = Object.entries(content).find(([mediaType]) =>
      mediaType.toLowerCase().startsWith('application/json;'),
    )
    if (jsonEntry) content['application/json'] = jsonEntry[1]
  }
  for (const nested of Object.values(value)) normalizeJsonMediaTypes(nested)
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}
